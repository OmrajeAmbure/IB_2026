# Salary Calculations
base_salary = int(input("Enter The Base Salary : ")) # A Base Salary is your fixed core pay
HRA = int(input("Enter Your HRA : ")) #  HRA (House Rent Allowance)
Bonus = int(input("Enter Your Bonus : ")) # performance Reward

salary = base_salary + HRA + Bonus
print("Salary : ",salary) 